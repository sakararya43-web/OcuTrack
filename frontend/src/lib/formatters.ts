export function formatStatusLabel(status: string | null | undefined): string {
  if (!status) return 'Unknown';
  return status
    .split('_')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}

/**
 * Normalizes backend review text for UI display without altering clinical meaning.
 * Replaces em dashes from backend static notices with standard punctuation.
 */
export function sanitizeClinicalText(text: string | null | undefined): string {
  if (!text) return '';
  return text.replace(/\s*\u2014\s*/g, ': ');
}
